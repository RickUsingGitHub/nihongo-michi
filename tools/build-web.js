// Writes src/sw.js, the web app's offline cache: node tools/build-web.js
// It lists every file the app loads (from index.html) and names the cache after a hash of their contents,
// so each new version replaces the old cache. Run it after changing anything in src/ (the GitHub Pages
// workflow runs it before publishing).
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const SRC = path.join(__dirname, '..', 'src');

const html = fs.readFileSync(path.join(SRC, 'index.html'), 'utf8');
const refs = [...html.matchAll(/(?:src|href)="([^"#:]+)"/g)].map(m => m[1]);
const files = ['index.html', ...refs];
for (const dir of ['icons', 'img']) for (const f of fs.readdirSync(path.join(SRC, dir))) files.push(dir + '/' + f);
const list = [...new Set(files)].filter(f => fs.existsSync(path.join(SRC, f)));
const missing = [...new Set(files)].filter(f => !fs.existsSync(path.join(SRC, f)));
if (missing.length) { console.error('missing files:', missing.join(', ')); process.exit(1); }

const hash = crypto.createHash('sha256');
for (const f of list) hash.update(f).update(fs.readFileSync(path.join(SRC, f)));
const version = 'michi-' + hash.digest('hex').slice(0, 12);

const sw = `/* Offline cache for the Nihongo Michi web app. Generated by tools/build-web.js — do not edit. */
const VERSION = '${version}';
const FILES = ${JSON.stringify(['./', ...list], null, 2)};

self.addEventListener('install', e => {
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k !== VERSION).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

// The app's own files come from the cache (so it works offline); everything else goes to the network.
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req)));
});
`;
fs.writeFileSync(path.join(SRC, 'sw.js'), sw);
const bytes = list.reduce((s, f) => s + fs.statSync(path.join(SRC, f)).size, 0);
console.log(`sw.js: ${list.length} files, ${(bytes / 1048576).toFixed(1)} MB, cache ${version}`);
