const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const RAW = path.join(__dirname, 'raw');
const OUT = path.join(__dirname, '..', 'src', 'data', 'gen');
fs.mkdirSync(OUT, { recursive: true });

const KANJI_RE = /[㐀-䶿一-鿿豈-﫿々〆ヶ]/;
const kataToHira = s => s.replace(/[ァ-ヶ]/g, c => String.fromCharCode(c.charCodeAt(0) - 0x60));
const escapeRe = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') q = false;
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.length > 1 || row[0] !== '') rows.push(row);
      row = [];
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

// Build furigana markup: 食べ物 + たべもの -> 食[た]べ物[もの]; falls back to {expr|reading}.
function align(expr, reading) {
  if (!KANJI_RE.test(expr)) return expr;
  // a few list entries put the ～ only on the reading (我 / が～): put it on the word too
  if (/^[～〜]/.test(reading) && !/^[～〜]/.test(expr)) expr = '～' + expr;
  if (/[～〜]$/.test(reading) && !/[～〜]$/.test(expr)) expr += '～';
  const pre = expr.match(/^[～〜]*/)[0], post = expr.match(/[～〜]*$/)[0];
  if (pre || post) {
    const strip = s => s.replace(/^[～〜]+|[～〜]+$/g, '');
    return pre + align(strip(expr), strip(reading)) + post;
  }
  const segs = [];
  for (const ch of expr) {
    const k = KANJI_RE.test(ch);
    if (segs.length && segs[segs.length - 1].k === k) segs[segs.length - 1].t += ch;
    else segs.push({ k, t: ch });
  }
  const pattern = '^' + segs.map(s => (s.k ? '(.+?)' : escapeRe(kataToHira(s.t)))).join('') + '$';
  const m = kataToHira(reading).match(new RegExp(pattern));
  if (!m) return `{${expr}|${reading}}`;
  let g = 1;
  return segs.map(s => (s.k ? `${s.t}[${m[g++]}]` : s.t)).join('');
}

function cleanMeaning(m) {
  m = m.replace(/\s+/g, ' ').trim();
  const parts = m.split(/;\s*/);
  let out = parts[0];
  for (const p of parts.slice(1)) { if ((out + '; ' + p).length > 70) break; out += '; ' + p; }
  if (out.length > 90) out = out.slice(0, 87).replace(/[ ,;]+[^ ,;]*$/, '') + '…';
  return out;
}

// ---------- vocabulary ----------
const seen = new Map();
const vocab = { 5: [], 4: [], 3: [], 2: [], 1: [] };
const anomalies = [];
const FIX_SPELLING = { 田ぼ: '田んぼ' };   // typos in the source lists
for (const lvl of [5, 4, 3, 2, 1]) {
  const rows = parseCsv(fs.readFileSync(path.join(RAW, `n${lvl}.csv`), 'utf8'));
  rows.shift();
  for (const r of rows) {
    let [expr, reading, meaning] = r;
    if (!expr || !meaning) continue;
    // "堅; 硬; 固い": the okurigana on the last spelling belongs to the first one too
    const variants = expr.trim().split(/[／/;；、]/).map(s => s.replace(/\s+/g, ''));
    expr = variants[0];
    const tail = variants[variants.length - 1].match(/[ぁ-ゖ]+$/);
    if (variants.length > 1 && tail && !/[ぁ-ゖ]$/.test(expr)) expr += tail[0];
    reading = (reading || expr).trim().split(/[／/;；、,]/)[0].replace(/\s+/g, '');
    // する-verbs listed with する only in the reading (運動 / うんどうする): keep the noun
    if (/.する$/.test(reading) && !/[ぁ-ゖ]$/.test(expr)) reading = reading.slice(0, -2);
    expr = FIX_SPELLING[expr] || expr;
    if (/[（(]/.test(expr)) { anomalies.push(expr); expr = expr.replace(/[（(].*?[）)]/g, ''); }
    if (/[（(]/.test(reading)) reading = reading.replace(/[（(].*?[）)]/g, '');
    const key = expr + '|' + reading;
    if (seen.has(key)) continue;
    seen.set(key, lvl);
    vocab[lvl].push([align(expr, reading), cleanMeaning(meaning)]);
  }
}
const vocabJs = '// Generated by tools/build-data.js - JLPT vocabulary (Waller lists, CC BY; meanings JMdict, CC BY-SA)\n' +
  'window.JT = window.JT || {};\nJT.VOCAB = ' + JSON.stringify(vocab).replace(/\],\[/g, '],\n[') + ';\n';
fs.writeFileSync(path.join(OUT, 'vocab.js'), vocabJs);

