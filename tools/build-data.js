const kanjiOut = [];
for (const [ch, d] of Object.entries(kj)) {
  // a few kanji (e.g. 分) only carry the pre-2010 level; map old 4/3/2/1 to N5/N4/N3/N1
  if (!d.jlpt_new && d.jlpt_old) d.jlpt_new = { 4: 5, 3: 4, 2: 3, 1: 1 }[d.jlpt_old];
  if (!d.jlpt_new) continue;
  // Our own keywords for beginner kanji whose KANJIDIC order leads with a rare sense, otherwise
  // KANJIDIC meanings minus notes such as "(kokuji)" and measures like "shaku/100"
  const meanings = KEYWORDS[ch] ? KEYWORDS[ch].split(', ') : [];
  for (const x of KEYWORDS[ch] ? [] : d.meanings || []) {
    const m = x.replace(/\s*\((kokuji|kun|ateji)\)\s*/gi, '').trim();
    if (!m || /^\(.*\)$/.test(m) || /[/%0-9]/.test(m)) continue;
    if (!meanings.some(y => y.toLowerCase() === m.toLowerCase())) meanings.push(m);
  }
  if (!meanings.length) for (const x of d.meanings || []) meanings.push(x.replace(/\s*\(kokuji\)/i, ''));
  const on = (d.readings_on || []).map(hiraToKata).slice(0, 4);
  const kun = (d.readings_kun || []).slice(0, 5);
  const ex = allWords
    .filter(w => w.m.includes(ch) && w.lvl >= d.jlpt_new - 1)
    .sort((a, b) => b.lvl - a.lvl || a.m.length - b.m.length)
    .slice(0, 4)
    .map(w => w.m + '=' + w.en.split(/[;,]/)[0]);
  const meaningText = meanings.slice(0, 4).join(', ').toLowerCase()
    .replace(/\b(japan|japanese|china|chinese|korea|buddha|buddhist|shinto|america|england|english|europe|asia|western|sino|saturday|spain|france|germany|russia|india|holland|italy|portugal|britain|mexico|turkey|i)\b/g, w => w[0].toUpperCase() + w.slice(1));
  kanjiOut.push([ch, d.jlpt_new, d.strokes, meaningText, on.join('、'), kun.join('、'), d.freq || 9999, ex.join(';')]);
}
kanjiOut.sort((a, b) => b[1] - a[1] || a[6] - b[6]);
const counts = {};
for (const k of kanjiOut) counts[k[1]] = (counts[k[1]] || 0) + 1;
